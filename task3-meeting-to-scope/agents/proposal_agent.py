from datetime import datetime, timezone
from typing import Dict

class ProposalAgent:
    """
    Proposal Agent: Synthesizes Scope of Work, Technical Feasibility, and Task Estimates
    into a client-ready proposal document requiring human consultant sign-off.
    """

    def generate_proposal(self, scope: Dict, estimates: Dict) -> Dict:
        now_str = datetime.now(timezone.utc).strftime("%B %d, %Y")
        totals = estimates["totals"]
        costs = estimates["estimated_investment_usd"]

        proposal_text = f"""# Professional Services Proposal: {scope['project_name']}
**Prepared For:** {scope['client_name']}
**Date:** {now_str}
**Target Delivery:** {scope['target_timeline']}
**Prepared By:** AI Tech Consulting Services

---

## 1. Executive Summary
LocalTrades requires a high-performance, conversion-optimized trade contractor directory. By leveraging Brilliant Directories' native platform architecture, we eliminate redundant custom coding, dramatically lower implementation costs, and guarantee a rapid, stable launch.

## 2. Solution Architecture & Feasibility
Our technical feasibility analysis confirmed that the majority of core business requirements (Stripe Connect, radius search filtering, membership tiers, and lead distribution) are supported directly via built-in platform settings. This architecture delivers an estimated **$4,000+ in development savings** while providing an enterprise-grade foundation.

## 3. Scope of Deliverables
"""
        for d in scope["deliverables"]:
            source_note = ""
            if d.get("documentation_citation"):
                source_note = f" *(Ref: [{d['documentation_citation']['title']}]({d['documentation_citation']['url']}))*"
            proposal_text += f"- **{d['deliverable_id']}: {d['title']}**\n  {d['description']}\n  *Implementation:* {d['implementation_strategy']}{source_note}\n\n"

        proposal_text += f"""## 4. Effort & Investment Breakdown
- **Estimated Development Effort:** {totals['likely_hours']} hours (Range: {totals['low_hours']}h – {totals['high_hours']}h)
- **Consulting Rate:** ${estimates['hourly_rate_usd']:.0f} / hour
- **Recommended Fixed Investment:** **${costs['recommended_fixed_quote']:,.2f} USD**

## 5. Milestone Schedule ({scope['target_timeline']})
1. **Milestone 1 (Days 1–3):** Admin environment setup, Stripe Connect activation & membership pricing tiers.
2. **Milestone 2 (Days 4–7):** Search radius configuration, sidebar filters widget, and brand CSS styling overrides.
3. **Milestone 3 (Days 8–10):** Lead routing rules, end-to-end transaction QA, and production launch cutover.

## 6. Explicit Exclusions & Platform Boundaries
To protect project velocity and budget, the following items are outside the scope of this web platform proposal:
"""
        for exc in scope["exclusions"]:
            proposal_text += f"- {exc}\n"

        proposal_text += f"""
## 7. Client Sign-Off & Approval
*Notice: This proposal is generated by the AI Tech Consultant Agent Team and requires formal human consultant review prior to client delivery.*

- **Consultant Status:** Pending Senior Review
- **Client Acceptance Signature:** ___________________________  **Date:** ____________
"""

        return {
            "proposal_title": f"Proposal: {scope['project_name']}",
            "generated_date": now_str,
            "target_timeline": scope["target_timeline"],
            "total_likely_hours": totals["likely_hours"],
            "total_investment_usd": costs["recommended_fixed_quote"],
            "markdown_proposal": proposal_text,
            "status": "pending_human_approval",
            "approved_by": None,
            "approved_at": None
        }
